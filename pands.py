import pandas as pd
df=pd.read_csv(r"C:\Users\HP\Desktop\Arunproject2\online_retail_project.csv")
print(df)
print(df.head(10))
print(df.tail(10))
print(df.shape)
print(df.columns)
print(df.info())
print(df.describe())
print(df.nunique())
print(df.isnull().sum())
print(df.duplicated().sum())
print(df[df["Quantity"]<=0])
print(df[df["UnitPrice"]<=0])
print(df["InvoiceDate"].isnull().sum())
df["InvoiceDate"]=pd.to_datetime(df["InvoiceDate"],errors="coerce")
for col in["ProductName","Country","SalesChannel"]:
    print("\nunique Values in",col)
    print(df[col].dropna().unique())
df=df.drop_duplicates()
print(df.shape)
df=df.dropna(subset=["CustomerID"])
print(df["CustomerID"].isnull().sum())
df["Country"]=df["Country"].str.strip()
df["Country"]=df["Country"].ffill()
df["Country"]=df["Country"].replace({"UKK":"United Kingdom"})
print(df["Country"].isnull().sum())
df["ProductName"]=df["ProductName"].str.strip()
df["ProductName"]=df["ProductName"].ffill()
df["ProductName"]=df["ProductName"].replace({"Wireless Mous":"Wireless Mouse"})
print(df["ProductName"].isnull().sum())
df['InvoiceDate'] = pd.to_datetime(df['InvoiceDate'], errors='coerce')
df['InvoiceDate'] = df['InvoiceDate'].ffill()
print(df["InvoiceDate"].isnull().sum())
df['UnitPrice'] = df['UnitPrice'].fillna(df['UnitPrice'].mean())
print(df["UnitPrice"].isnull().sum())
df['SalesChannel'] = df['SalesChannel'].ffill()
print(df["SalesChannel"].isnull().sum())
print(df.isnull().sum())
print(df["Country"].value_counts().sort_index())
print(df["ProductName"].value_counts().sort_index())
df.to_csv("online_retail_project.csv",index=False)